// Builds every Word document that is not a case document, from its markdown source.
// Usage, from this folder, with the docx npm package installed:
//   node build.js
// Paths are relative to the output/ folder.
const path = require("path");
const { convert } = require("./md2docx");

const OUTPUT = path.resolve(__dirname, "..", "..");
const TITLE = "Campus Comps: Building a Data Website with an AI Coding Agent";
const AUTHOR = "[Author name]";

const DOCUMENTS = [
  {
    source: "students/data_description_sheet.md",
    output: "students/Data Description Sheet.docx",
    header: "College-town home sales dataset: Data description sheet",
    subtitle: "Version 1.0",
  },
  {
    // Generated by instructor/reference-code/run_all.py. Do not edit the markdown by hand.
    source: "source/word-documents/variation2_answer_key.md",
    output: "instructor/Variation 2 Answer Key.docx",
    header: "Campus Comps case: Variation 2 Answer Key (instructors only)",
    subtitle: TITLE,
    author: AUTHOR,
  },
  {
    // Data figures filled in by instructor/reference-code/run_all.py from templates/instructor_orientation.md.
    source: "source/word-documents/instructor_orientation.md",
    output: "instructor/Instructor Orientation.docx",
    header: "Campus Comps case: Instructor Orientation",
    subtitle: TITLE,
    author: AUTHOR,
  },
  {
    source: "source/word-documents/post_assignment_survey.md",
    output: "instructor/Post-Assignment Survey.docx",
    header: "Campus Comps case: Post-Assignment Survey",
    subtitle: TITLE,
    author: AUTHOR,
  },
];

async function main() {
  for (const d of DOCUMENTS) {
    await convert({
      ...d,
      source: path.join(OUTPUT, d.source),
      output: path.join(OUTPUT, d.output),
    });
    console.log("wrote", d.output);
  }
}

module.exports = { TITLE, AUTHOR };
if (require.main === module) main().catch((e) => { console.error(e); process.exit(1); });
